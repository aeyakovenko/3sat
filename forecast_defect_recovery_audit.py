"""Recover the defects of a nonlinear binary forecast using folded row spans.

The linear comparison rule is y[t] = y[t-B] + impulse[t] over F_2, B=2**h.
Its impulse response at s is the ray t=s,s+B,... . The verifier never builds
a timestamp truth table. The independent test oracle takes ordinary time steps.
"""

from functools import lru_cache
from itertools import chain
from random import Random


def parity_set(items):
    result = set()
    for item in items:
        result.symmetric_difference_update((item,))
    return result


def shifted_rays(B, seeds, impulses, lag):
    # Nonnegative y is generated by the impulses plus the seeds immediately
    # preceding time zero. Separate point indicators supply y[t-lag] at
    # genuinely negative seed times. A point equals two consecutive rays.
    starts = [lag+i for i in impulses]
    starts.extend(lag+B+i for i in seeds if -B <= i < 0)
    for i in seeds:
        if lag+i >= 0:
            starts.extend((lag+i, lag+i+B))
    return parity_set(s for s in starts if s < B*B)


def defect_terms(B, seeds, impulses, left, right):
    def bank(lags):
        return parity_set(chain.from_iterable(shifted_rays(B, seeds, impulses, lag)
                                              for lag in lags))

    # Each pair remains a product of two ray automata evaluated on the same
    # timestamp. Identical ordered monomials cancel in F_2.
    left_rays, right_rays = bank(left), bank(right)
    linear = ((x,) for x in bank([0]))
    products = (tuple(sorted((x, y))) for x in left_rays for y in right_rays)
    return sorted(parity_set(chain(linear, products)))


def binary_basis(vectors):
    pivots = {}
    for row in vectors:
        while row:
            pivot = row.bit_length()-1
            if pivot not in pivots:
                pivots[pivot] = row
                break
            row ^= pivots[pivot]
    return tuple(pivots.values())


class FoldedDefect:
    def __init__(self, h, terms):
        self.h = h
        self.start = self.final = 0
        self.prefix_nonzero = lru_cache(maxsize=None)(self._prefix_nonzero)
        self.moves = [[[] for _ in range(4)] for _ in range(h)]
        base = 0
        for term in terms:
            states = 1 << len(term)
            all_ge = 1 << (base+states-1)
            self.start |= all_ge
            self.final |= all_ge
            for j in range(h):
                for column in range(4):
                    low, high = column % 2, column // 2
                    mismatch = any(((s >> j) & 1) != low for s in term)
                    for flags in range(states):
                        updated = flags
                        for i, s in enumerate(term):
                            bound_bit = (s >> (h+j)) & 1
                            if high != bound_bit:
                                # Reading little-endian, this new bit overrides
                                # comparison with every less significant bit.
                                updated = (updated & ~(1 << i)) | (high << i)
                        self.moves[j][column].append(0 if mismatch else 1 << (base+updated))
            base += states

    def _prefix_nonzero(self, pinned, value):
        rows = (self.start,) if self.start else ()
        for j, matrices in enumerate(self.moves):
            columns = tuple((c % 2 << j) | (c // 2 << (self.h+j)) for c in range(4))
            layer_mask = (1 << j) | (1 << (self.h+j))
            images = []
            for column, matrix in zip(columns, matrices):
                if (column ^ value) & pinned & layer_mask:
                    continue
                for row in rows:
                    image = 0
                    while row:
                        bit = row & -row
                        image ^= matrix[bit.bit_length()-1]
                        row ^= bit
                    images.append(image)
            rows = binary_basis(images)
        return any((r & self.final).bit_count() % 2 for r in rows)

    def interval_nonzero(self, lo, hi):
        # Partition the integer interval into aligned dyadic prefix blocks.
        full = (1 << (2*self.h))-1
        while lo <= hi:
            size = 1 << ((hi-lo+1).bit_length()-1)
            if lo:
                size = min(size, lo & -lo)
            if self.prefix_nonzero(full ^ (size-1), lo):
                return True
            lo += size
        return False

    def first(self, horizon):
        if not self.interval_nonzero(0, horizon):
            return None
        lo, hi = 0, horizon
        while lo < hi:
            middle = (lo+hi)//2
            if self.interval_nonzero(lo, middle):
                hi = middle
            else:
                lo = middle+1
        return lo


def audit(h, horizon, left, right, seeds):
    B = 1 << h
    def nonlinear(values, t):
        a = sum(values.get(t-lag, 0) for lag in left) % 2
        b = sum(values.get(t-lag, 0) for lag in right) % 2
        return a*b

    true = dict.fromkeys(seeds, 1)
    for t in range(horizon+1):
        true[t] = nonlinear(true, t)
    expected = [t for t in range(horizon+1) if true[t] != true.get(t-B, 0)]
    impulses, interval_checks, timestamp_checks = [], 0, 0
    rng = Random(100*h+horizon)
    while True:
        verifier = FoldedDefect(h, defect_terms(B, seeds, impulses, left, right))
        candidate = dict.fromkeys(seeds, 1)
        failures = []
        for t in range(horizon+1):
            candidate[t] = candidate.get(t-B, 0) ^ int(t in impulses)
            if candidate[t] != nonlinear(candidate, t):
                failures.append(t)
        full = B*B-1
        failure_set = set(failures)
        assert all(verifier.prefix_nonzero(full, t) == (t in failure_set)
                   for t in range(horizon+1))
        timestamp_checks += horizon+1
        for _ in range(24):
            lo, hi = sorted(rng.choices(range(horizon+1), k=2))
            assert verifier.interval_nonzero(lo, hi) == any(lo <= t <= hi for t in failures)
            interval_checks += 1
        first = verifier.first(horizon)
        assert first == next(iter(failures), None)
        if first is None:
            assert impulses == expected and candidate == true
            break
        assert not impulses or impulses[-1] < first
        impulses.append(first)
    return len(impulses), interval_checks, timestamp_checks


if __name__ == '__main__':
    cases = [(2, 15, (1, 5), (2, 3), {-2, -1}), (3, 57, (1, 2), (3, 9), {-2, -1}),
             (4, 211, (1, 2), (3, 17), {-2, -1}), (3, 63, (1, 8), (2, 3), set())]
    outcomes = [audit(*case) for case in cases]
    print('recovered', [count for count, _, _ in outcomes], 'defects;',
          sum(checks for _, checks, _ in outcomes), 'interval and',
          sum(checks for _, _, checks in outcomes), 'timestamp comparisons passed')

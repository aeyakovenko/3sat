"""Splice an idle return into an ordinary 3-CNF with a Beneš memory router."""

from itertools import product


class CNF:
    def __init__(self):
        self.owner = None
        self.bits = [False]
        self.clauses = []

    def bit(self, value):
        self.bits.append(bool(value))
        return len(self.bits) - 1

    def value(self, lit):
        return self.bits[abs(lit)] == (lit > 0)

    def clause(self, *lits):
        assert 1 <= len(lits) <= 3
        self.clauses.append((self.owner, lits + (lits[-1],) * (3 - len(lits))))

    def both(self, a, b):
        out = self.bit(self.value(a) and self.value(b))
        self.clause(-out, a)
        self.clause(-out, b)
        self.clause(out, -a, -b)
        return out

    def either(self, a, b):
        return -self.both(-a, -b)

    def select(self, control, yes, no):
        out = self.bit(self.value(yes if self.value(control) else no))
        self.clause(-control, -yes, out)
        self.clause(-control, yes, -out)
        self.clause(control, -no, out)
        self.clause(control, no, -out)
        return out

    def equal_if(self, guard, a, b):
        self.clause(-guard, -a, b)
        self.clause(-guard, a, -b)

    def switch(self, first, second, swap):
        # One shared switch choice for both lanes and every record bit.
        s = self.bit(swap)
        return ([self.select(s, b, a) for a, b in zip(first, second)],
                [self.select(s, a, b) for a, b in zip(first, second)])


def route(cnf, lanes, dest):
    """Two-color the edges connecting outer input-pairs and output-pairs."""
    n = len(lanes)
    if n == 2:
        return cnf.switch(*lanes, dest[0] == 1)
    inverse = [dest.index(i) for i in range(n)]
    color = [None] * n
    for first in range(n):
        if color[first] is not None:
            continue
        color[first] = 0
        queue = [first]
        while queue:
            i = queue.pop()
            for neighbor in (i ^ 1, inverse[dest[i] ^ 1]):
                if color[neighbor] is None:
                    color[neighbor] = 1 - color[i]
                    queue.append(neighbor)
                assert color[neighbor] != color[i]
    top, bottom, upper_dest, lower_dest = [], [], [], []
    for i in range(0, n, 2):
        swap = color[i]
        upper, lower = cnf.switch(lanes[i], lanes[i + 1], swap)
        top.append(upper)
        bottom.append(lower)
        upper_dest.append(dest[i + swap] // 2)
        lower_dest.append(dest[i + 1 - swap] // 2)
    top = route(cnf, top, upper_dest)
    bottom = route(cnf, bottom, lower_dest)
    output = []
    for j, (upper, lower) in enumerate(zip(top, bottom)):
        output.extend(cnf.switch(upper, lower, color[inverse[2 * j]]))
    return output


def word(value, width):
    return [(value >> shift) & 1 for shift in reversed(range(width))]


def build(horizon, constant, pin, cut):
    """PCs 0,1,2 store a constant, load it into RESULT, and erase. PC 3 idles."""
    cnf = CNF()
    true = cnf.bit(True)
    cnf.clause(true)
    false = -true
    bits = lambda n, w: [cnf.bit(b) for b in word(n, w)]
    addr = constant & 1
    width = (horizon - 1).bit_length()

    def controller(t):
        if cut is not None and t > cut:
            return 3, pin
        return min(t, 3), constant if t >= 2 else 0

    pcs, regs = [], []
    for t in range(horizon + 1):
        pc, reg = controller(t)
        pcs.append([cnf.bit(pc == i) for i in range(4)])
        regs.append(bits(reg, 2))
    for i in range(4):
        cnf.clause(pcs[0][i] if i == 0 else -pcs[0][i])
    for b in regs[0]:
        cnf.clause(-b)

    events = []
    keys = []
    for t in range(horizon):
        cnf.owner = t
        # Keep the cut edge's event exactly as generated by the genuine run.
        valid = t < 3 and (cut is None or t <= cut)
        writes = valid and t != 1
        value = constant if valid and t < 2 else 0
        row = [cnf.bit(valid), cnf.bit(writes), cnf.bit(addr if valid else 0),
               *bits(value, 2), *bits(t, width)]
        events.append(row)
        keys.append((not valid, addr if valid else 0, t))
        for oldpc, guard in enumerate(pcs[t]):
            for newpc, b in enumerate(pcs[t + 1]):
                cnf.clause(-guard, b if newpc == min(3, oldpc + 1) else -b)
            expected = oldpc != 3, oldpc in (0, 2), bool(addr) and oldpc != 3
            for b, on in zip(row[:3], expected):
                cnf.clause(-guard, b if on else -b)
            if oldpc != 1:
                for b, v in zip(row[3:5], word(constant if oldpc == 0 else 0, 2)):
                    cnf.clause(-guard, b if v else -b)
            for dst, src in zip(regs[t + 1], row[3:5] if oldpc == 1 else regs[t]):
                cnf.equal_if(guard, dst, src)
        for b, v in zip(row[5:], word(t, width)):
            cnf.clause(b if v else -b)

    cnf.owner = None
    order = sorted(range(horizon), key=keys.__getitem__)
    ordered = route(cnf, events, [order.index(i) for i in range(horizon)])
    last = None
    for row in ordered:
        # Compare composite keys, with dummy records last, then address and time.
        key = [-row[0], row[2], *row[5:]]
        same = false
        if last is not None:
            old_key = [-last[0], last[2], *last[5:]]
            equal_prefix = true
            for x, y in zip(old_key, key):
                cnf.clause(-equal_prefix, -x, y)
                equal_prefix = cnf.both(equal_prefix, cnf.select(x, y, -y))
            same = cnf.both(last[0], cnf.select(last[2], row[2], -row[2]))
        read = cnf.both(row[0], -row[1])
        for q, bit in enumerate(row[3:5]):
            prior = false if last is None else cnf.both(same, last[3 + q])
            cnf.equal_if(read, bit, prior)
        last = row

    cnf.clause(pcs[-1][3])
    flags = []
    for candidate in range(4):
        x, y = [b if v else -b for b, v in zip(regs[-1], word(candidate, 2))]
        flags.append(cnf.both(x, y))
    for i in range(4):
        for j in range(i):
            cnf.clause(-flags[i], -flags[j])
    cnf.clause(flags[pin])
    return cnf


def bad_owners(cnf):
    return {owner for owner, clause in cnf.clauses if not any(map(cnf.value, clause))}


def main():
    count = 0
    for h, constant in product((4, 8, 16), range(1, 4)):
        assert not bad_owners(build(h, constant, constant, None))
        for pin in range(4):
            if pin == constant:
                continue
            original = build(h, constant, pin, None)
            assert bad_owners(original) == {None}
            for cut in range(h):
                repaired = build(h, constant, pin, cut)
                assert repaired.clauses == original.clauses  # identical physical CNF
                assert bad_owners(repaired) == {cut}
                count += 1
    print(f"{count} single-edge repairs passed on fixed ordinary 3-CNFs")


if __name__ == "__main__":
    main()

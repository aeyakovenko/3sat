#!/usr/bin/env python3
"""Build fooling_family_dispatcher.asm: one program for F3, F2, restricted F1, F4, the k-region family and the proof's F5,
by concatenating the component deciders with renamed registers (each component then starts from zero
registers, as it assumes) and prefixed labels, behind a test on the first file word.
Changes to components (stated in the note): table_index_tree_walk.asm sets a flag at every pass-1 pin clause and, if
the file had no pin clause, hands over to the k-region pin table after its first pass; the k-region pin
table keeps its name table at Z0 + j (Z0 = all '0' digits) instead of P + j, so that the first pass's
stores (which lie near P, 0x2d.., 0x3a.., 0x62.. in the top byte) cannot meet it.
Run from audits/: python3 fooling_family_dispatcher_build.py [--out DIR]
It builds the program in memory, prints the instruction counts and checks that the result is identical to
fooling_family_dispatcher.asm; with --out DIR it also writes the program there. Nothing else is written."""
import re, sys
sys.dont_write_bytecode = True
import five_slot_ram_interpreter as J

OPS = {'add', 'sub', 'mul', 'and', 'or', 'xor', 'shl', 'shr', 'eq', 'ne', 'ltu', 'mov'}
CMPS = {'eq', 'ne', 'ltu', 'geu'}


def rename(text, rp, lp, start):
    out = []
    first = True
    for raw in text.splitlines():
        s = raw.split('#', 1)[0].strip()
        if not s:
            continue
        lab = None
        m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$', s)
        if m:
            lab, s = m.group(1), m.group(2)
        succ = None
        if '->' in s:
            s, succ = [x.strip() for x in s.split('->')]
        tok = s.split()
        R = lambda x: x if re.fullmatch(r'-?\d+', x) else rp + x
        T = lambda x: x if x in ('YES', 'NO') else lp + x
        if tok[0] == 'br':
            tok = ['br', tok[1], R(tok[2]), R(tok[3]), T(tok[4]), T(tok[5])]
        elif tok[0] == 'store':
            tok = ['store', R(tok[1]), R(tok[2])]
        else:
            if tok[2] == 'load':
                tok = [R(tok[0]), '=', 'load', R(tok[3])]
            else:
                tok = [R(tok[0]), '=', tok[2]] + [R(x) for x in tok[3:]]
        line = ' '.join(tok) + ((' -> ' + T(succ)) if succ else '')
        labs = []
        if first:
            labs.append(start); first = False
        if lab:
            labs.append(lp + lab)
        # a line may carry two labels: emit the start label on its own via a jump-free alias
        out.append((labs, line))
    lines = []
    for labs, line in out:
        if len(labs) == 2:   # start label and original label on the same line: keep one, alias the other
            lines.append('%s: %s' % (labs[1], line))
            lines.insert(len(lines) - 1, '#alias %s %s' % (labs[0], labs[1]))
        elif labs:
            lines.append('%s: %s' % (labs[0], line))
        else:
            lines.append('      ' + line)
    return lines


def resolve_alias(lines):
    alias = {}
    for l in lines:
        if l.startswith('#alias'):
            _, a, b = l.split(); alias[a] = b
    res = []
    for l in lines:
        if l.startswith('#alias'):
            continue
        for a, b in alias.items():
            l = re.sub(r'\b%s\b' % a, b, l)
        res.append(l)
    return res


f5 = open('table_index_tree_walk.asm').read()
f5 = f5.replace('E1:   m = mov 1', 'E1:   br eq g 0 KR E2\nE2:   m = mov 1')
f5 = f5.replace('PS:   c = add a3 k1\n      store c a1 -> M0', 'PS:   c = add a3 k1\n      store c a1\n      g = mov 1 -> M0')
assert 'g = mov 1 -> M0' in f5 and 'br eq g 0 KR E2' in f5
kr = open('k_region_pin_table.asm').read()
assert kr.count('c = add j v') == 1
kr = kr.replace('c = add j v', 'c = add j z')

head = ['# Dispatcher (generated by fooling_family_dispatcher_build.py).  Word 0 decides the family:',
        '#   exactly "p " (w = 16)            -> F3, the four 87-byte files',
        '#   low three bytes "p  "             -> F2, the five-slot aligned header',
        '#   byte 6 is "2" ("p cnf 20", W >= 7) -> restricted F1 (forced widths 224..512)',
        '#   otherwise                         -> F5 tree walk; if its first pass saw no pin clause,',
        '#                                        the k-region pin table (F4 and k-region files)',
        'D0: dx = load 0',
        '      br eq dx 8304 S3 D1',
        'D1: dc = and dx 16777215',
        '      br eq dc 2105456 S2 D2',
        'D2: dc = shr dx 24',
        '      dc = shr dc 24',   # two shifts of 24 < w, so both shift conventions agree
        '      dc = and dc 255',
        '      br eq dc 50 S1 S5']
body = []
body += ['# F3: four_file_four_instructions.asm'] + rename(open('four_file_four_instructions.asm').read(), 'qc', 'C3_', 'S3')
body += ['# F2: two_low_bit_count.asm'] + rename(open('two_low_bit_count.asm').read(), 'qb', 'C2_', 'S2')
body += ['# F1: sign_edit_periodic_scan.asm'] + rename(open('sign_edit_periodic_scan.asm').read(), 'qa', 'C1_', 'S1')
f5lines = rename(f5, 'qf', 'C5_', 'S5')
f5lines = [l.replace('C5_KR', 'SK') for l in f5lines]
body += ['# F5: table_index_tree_walk.asm with the pin flag and the hand-over'] + f5lines
body += ['# F4 and k-region: k_region_pin_table.asm with its table at Z0 + j'] + rename(kr, 'qk', 'CK_', 'SK')
text = '\n'.join(resolve_alias(head + body)) + '\n'
if '--out' in sys.argv:
    import os
    out = sys.argv[sys.argv.index('--out') + 1]
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, 'fooling_family_dispatcher.asm'), 'w').write(text)
prog = J.parse(text)
print('fooling_family_dispatcher.asm: %d stored instructions (head 8, F3 4, F2 7, F1 8, F5 52, k-region 28)' % len(prog))
same = open('fooling_family_dispatcher.asm').read() == text
print('identical to the stored fooling_family_dispatcher.asm:', same)
sys.exit(0 if same else 1)

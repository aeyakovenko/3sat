"""Kernel-based exhaustion for XOR/AND complexity of 2 x 2 binary products.

Constants and all affine wires are free. A truth table is a Python integer
whose bit positions enumerate points of a homogeneous input hyperplane.
Run with no arguments for all six orbits, with --all for all 255 hyperplanes,
or give one or more decimal normals.
"""

import argparse
from itertools import combinations


class Basis:
    """Echelon rows of a vector space over F2."""

    def __init__(self, vectors=()):
        self.rows = {}
        self.ordered = []
        for vector in vectors:
            self.add(vector)

    def reduce(self, vector):
        for pivot, row in self.ordered:
            if vector & pivot:
                vector ^= row
        return vector

    def add(self, vector):
        vector = self.reduce(vector)
        if vector:
            self.rows[1 << (vector.bit_length() - 1)] = vector
            self.ordered = sorted(self.rows.items(), reverse=True)
        return bool(vector)

    def vectors(self):
        values = [0]
        for row in self.rows.values():
            values += [row ^ value for value in values]
        return values


def multiply(a, b):
    product = 0
    for i in range(2):
        for j in range(2):
            value = 0
            for k in range(2):
                value ^= (a >> (2 * i + k)) & (b >> (2 * k + j)) & 1
            product |= value << (2 * i + j)
    return product


def transpose(matrix):
    return (matrix & 9) | ((matrix & 2) << 1) | ((matrix & 4) >> 1)


def check_seven_gate_upper_bound():
    for x in range(256):
        a, b, c, d, e, f, g, h = [(x >> i) & 1 for i in range(8)]
        p = (a ^ d) & (e ^ h)
        q = (c ^ d) & e
        r = a & (f ^ h)
        s = d & (g ^ e)
        t = (a ^ b) & h
        u = (c ^ a) & (e ^ f)
        v = (b ^ d) & (g ^ h)
        outputs = (p ^ s ^ t ^ v, r ^ t, q ^ s, p ^ q ^ r ^ u)
        assert sum(bit << i for i, bit in enumerate(outputs)) == multiply(x & 15, x >> 4)


def normal_orbits():
    # Row addition and a swap generate GL(2,2). A middle-index change
    # multiplies both inputs by inverse matrices; both generators square to I.
    def transform(generator, point):
        a, b = point & 15, point >> 4
        if generator == 6:
            return transpose(b) | (transpose(a) << 4)
        matrix = (6, 11)[generator % 2]
        if generator // 2 == 0:
            a = multiply(matrix, a)
        elif generator // 2 == 1:
            a, b = multiply(a, matrix), multiply(matrix, b)
        else:
            b = multiply(b, matrix)
        return a | (b << 4)

    wire_images = [[transform(g, 1 << i) for i in range(8)] for g in range(7)]
    orbit_sizes = {}
    unassigned = set(range(1, 256))
    while unassigned:
        representative = min(unassigned)
        orbit = {representative}
        pending = [representative]
        while pending:
            normal = pending.pop()
            for images in wire_images:
                image = sum((((normal & vector).bit_count() % 2) << i)
                            for i, vector in enumerate(images))
                if image not in orbit:
                    orbit.add(image)
                    pending.append(image)
        orbit_sizes[representative] = len(orbit)
        unassigned.difference_update(orbit)
    return orbit_sizes


def kernel_products(factor, sources, target_rows):
    """A basis of products factor*b whose image in the quotient is zero.

    Eliminate images of a basis of b's. Track their original products with
    the same XOR operations; each dependent column yields a kernel generator.
    """
    independent = {}
    for source in sources:
        product = factor & source
        remainder = product
        for pivot, row in target_rows:
            if remainder & pivot:
                remainder ^= row
        while remainder:
            pivot = remainder.bit_length() - 1
            if pivot not in independent:
                independent[pivot] = (remainder, product)
                break
            row, original = independent[pivot]
            remainder ^= row
            product ^= original
        else:
            yield product


def closure(initial, allowed, one):
    """Least subspace generated by legal AND gates staying inside allowed."""
    reached = Basis(initial)
    target = Basis(allowed)
    target_rows = target.ordered
    anchor = one & -one
    while len(reached.rows) < len(target.rows):
        sources = list(reached.rows.values())
        # Both a and its complement induce the same map into the quotient;
        # their products differ by b, already in the reached space.
        normalized = Basis(a ^ one if a & anchor else a for a in sources)
        for factor in normalized.vectors()[1:]:
            for product in kernel_products(factor, sources, target_rows):
                reached.add(product)
        if len(reached.rows) == len(sources):
            break
    return reached


def frame(normal):
    domain = [x for x in range(256) if (x & normal).bit_count() % 2 == 0]
    assert len(domain) == 128
    products = [multiply(x & 15, x >> 4) for x in domain]
    one = (1 << len(domain)) - 1

    def table(numbers, bit):
        return sum(((value >> bit) & 1) << index for index, value in enumerate(numbers))

    return one, [one] + [table(domain, i) for i in range(8)], [table(products, i) for i in range(4)]


def test_normal(normal):
    one, free, outputs = frame(normal)
    allowed = Basis(free + outputs)
    assert len(allowed.rows) - len(Basis(free).rows) == 4
    base = closure(free, free + outputs, one)
    assert any(base.reduce(output) for output in outputs)
    sources = list(base.rows.values())
    acceptable = set()
    for factor in base.vectors():
        if not factor or factor & 1:  # One representative up to complement.
            continue
        for side in (factor, one ^ factor):
            restricted = [source & side for source in sources]
            goals = [output & side for output in outputs]
            reachable = closure(restricted, restricted + goals, side)
            if any(reachable.reduce(goal) for goal in goals):
                break
        else:
            acceptable.add(factor)

    # Restricted to any fiber of a, b, or a+b, the escaping product a*b
    # is affine in the old wires. Each of those three factors must pass.
    planes = set()
    for a, b in combinations(acceptable, 2):
        if a ^ b in acceptable:
            planes.add(tuple(sorted((a, b, a ^ b))))
    cosets = {}
    for a, b, _ in planes:
        product = a & b
        remainder = allowed.reduce(product)
        if remainder:
            cosets.setdefault(remainder, product)
    passed = 0
    for product in cosets.values():
        # Enlarge only the allowed space. The actual new gate is then
        # generated from its factors. Every member of the same coset gives
        # exactly the same ambient space, regardless of which wire occurs.
        reachable = closure(sources, free + outputs + [product], one)
        if all(reachable.reduce(goal) == 0 for goal in outputs):
            passed += 1
    print(f"normal={normal} base_dim={len(base.rows)} factors={len(acceptable)} "
          f"planes={len(planes)} outside_cosets={len(cosets)} feasible={passed}",
          flush=True)
    assert passed == 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("normals", metavar="normal", type=int, nargs="*")
    parser.add_argument("--all", action="store_true", help="test all 255 hyperplanes directly")
    args = parser.parse_args()
    if args.all and args.normals:
        parser.error("choose --all or specific normals")
    if any(normal not in range(1, 256) for normal in args.normals):
        parser.error("each normal must be an integer from 1 through 255")
    check_seven_gate_upper_bound()
    print("Seven-AND construction agrees on all 256 inputs.", flush=True)
    orbits = normal_orbits()
    assert set(orbits) == {1, 6, 17, 18, 22, 102}
    print(f"Hyperplane orbit sizes: {orbits}", flush=True)
    for representative in (range(1, 256) if args.all else args.normals or orbits):
        test_normal(representative)
